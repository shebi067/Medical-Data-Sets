feature_cols = [c for c in df.columns if c not in ['row_id', 'class']]

iqr_records = []
for col in feature_cols:
    Q1 = df[col].quantile(0.25)
    Q3 = df[col].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR
    flagged_count = ((df[col] < lower_bound) | (df[col] > upper_bound)).sum()

    iqr_records.append({
        'Feature': col,
        'Q1': round(Q1, 2),
        'Q3': round(Q3, 2),
        'Lower Cutoff': round(lower_bound, 2),
        'Upper Cutoff': round(upper_bound, 2),
        'Flagged Outliers': flagged_count,
        'Treatment': 'Retained (valid clinical extremes; Random Forest is robust to outliers)'
    })

iqr_summary = pd.DataFrame(iqr_records)
print("--- IQR OUTLIER ANALYSIS ---")
display(iqr_summary)

