from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, f1_score


baseline_pipe = Pipeline([
    ('imputer', SimpleImputer(strategy='median')),
    ('model', DummyClassifier(strategy='most_frequent', random_state=RANDOM_STATE))
])
baseline_pipe.fit(X_train, y_train)
val_pred_base = baseline_pipe.predict(X_val)

base_val_acc = accuracy_score(y_val, val_pred_base)
base_val_f1 = f1_score(y_val, val_pred_base, average='macro', zero_division=0)

print("--- BASELINE MODEL (VALIDATION SET) ---")
print(f"Majority-Class Baseline -> Validation Accuracy: {base_val_acc:.4f} | Validation Macro F1: {base_val_f1:.4f}\n")

configs = [
    {'name': 'RF Config 1 (max_depth=3)',    'max_depth': 3},
    {'name': 'RF Config 2 (max_depth=6)',    'max_depth': 6},
    {'name': 'RF Config 3 (max_depth=None)', 'max_depth': None}
]

results_list = []
best_f1 = -1
best_config = None

for cfg in configs:
    rf_pipe = Pipeline([
        ('imputer', SimpleImputer(strategy='median')),
        ('model', RandomForestClassifier(
            n_estimators=100,
            max_depth=cfg['max_depth'],
            random_state=RANDOM_STATE
        ))
    ])


    rf_pipe.fit(X_train, y_train)


    val_preds = rf_pipe.predict(X_val)
    val_acc = accuracy_score(y_val, val_preds)
    val_macro_f1 = f1_score(y_val, val_preds, average='macro', zero_division=0)

    results_list.append({
        'Configuration': cfg['name'],
        'n_estimators (Fixed)': 100,
        'max_depth (Varied)': str(cfg['max_depth']),
        'Validation Accuracy': round(val_acc, 4),
        'Validation Macro F1': round(val_macro_f1, 4)
    })

    if val_macro_f1 > best_f1:
        best_f1 = val_macro_f1
        best_config = cfg

val_comparison_df = pd.DataFrame(results_list)
print("--- RANDOM FOREST VALIDATION COMPARISON TABLE ---")
display(val_comparison_df)

print(f"\nSelected Best Configuration: {best_config['name']} (Validation Macro F1 = {best_f1:.4f})")

